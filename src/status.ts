import { readdirSync } from 'node:fs';
import type { RigConfig } from './config.js';
import { lastBeat, type Beat } from './heartbeat.js';
import { readNight } from './digest/reader.js';
import type { RunStatus } from './digest/types.js';

export type NightStatusCounts = Record<RunStatus, number>;
export type NightOnDisk = { night: string; jobs: NightStatusCounts };

export type Status = {
  adapter: string;
  installed: string;
  lastBeat: Beat | null;
  nights: NightOnDisk[];
};

// Nights on disk = runs/<YYYY-MM-DD>.jsonl, newest first.
export function nightsOnDisk(runsDir: string): string[] {
  try {
    return readdirSync(runsDir)
      .filter((f) => /^\d{4}-\d{2}-\d{2}\.jsonl$/.test(f))
      .map((f) => f.slice(0, 10))
      .sort()
      .reverse();
  } catch {
    return [];
  }
}

export function readStatus(config: RigConfig): Status {
  return {
    adapter: config.adapter,
    installed: config.installed,
    lastBeat: lastBeat(),
    nights: nightsOnDisk(config.runsDir).map((night) => {
      const digest = readNight(config.runsDir, night);
      const jobs: NightStatusCounts = { ok: 0, retry: 0, fail: 0 };
      for (const row of digest?.rows ?? []) jobs[row.lastStatus]++;
      return { night, jobs };
    }),
  };
}
